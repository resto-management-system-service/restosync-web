// Regenerates .design-sync/assets/ds.in.css from the repo's "vercel" theme
// (DEFAULT_THEME) and compiles it to .design-sync/assets/ds.css with Tailwind.
//
//   node .design-sync/assets/build-css.mjs
//
// ds.css is what cfg.cssEntry points at — the converter copies it into the
// bundle as _ds_bundle.css and @imports it from styles.css. Tokens are
// promoted from [data-theme='vercel'] to :root so previews and generated
// designs render styled with no theme wrapper. Other repo themes stay in
// src/styles/themes/*.css and are not shipped.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '../..');
const themeCss = readFileSync(resolve(repo, 'src/styles/themes/vercel.css'), 'utf8');

const grab = (re) => {
  const m = themeCss.match(re);
  return m ? m[1].trim() : '';
};
const light = grab(/\[data-theme=['"]vercel['"]\]\s*\{([^}]+)\}/);
const dark = grab(/\[data-theme=['"]vercel['"]\]\.dark\s*\{([^}]+)\}/);
const themeInline = grab(/@theme inline\s*\{([\s\S]*?)\}\s*\}/);

const input = `/* Generated by .design-sync/assets/build-css.mjs — do not edit by hand.
   RestoSync UI tokens: the "vercel" theme (repo DEFAULT_THEME) promoted from
   [data-theme=vercel] to :root so DS previews and generated designs render
   styled without a theme wrapper. Regenerate with the command in this file's head. */
@import url("https://fonts.googleapis.com/css2?family=Geist:wght@300..700&family=Geist+Mono:wght@400..600&display=swap");
@import "tailwindcss" source(none);
@source "../../src/components/ui/**/*.{ts,tsx}";
@source "../../src/components/icons.tsx";
@source "../../src/components/forms/**/*.{ts,tsx}";
@source "../../src/components/modal/**/*.{ts,tsx}";
@source "../../src/hooks/**/*.{ts,tsx}";
@source "../previews/**/*.tsx";
@source inline("{,sm:,md:,lg:,dark:,hover:,focus:}{flex,inline-flex,grid,block,inline-block,hidden,flex-col,flex-row,flex-wrap,grid-cols-{1,2,3,4,5,6},col-span-{1,2,3,full},row-span-{1,2},items-{start,center,end,baseline},justify-{start,center,end,between},gap-{0,1,1.5,2,2.5,3,4,5,6,8,10,12},gap-x-{1,2,3,4,6},gap-y-{1,2,3,4,6},space-x-{1,2,3,4,6},-space-x-{1,2,3},space-y-{0,1,1.5,2,3,4,6,8},my-{1,2,3,4,6},mx-auto,ring-2,ring-background,p-{0,1,2,3,4,5,6,8},px-{1,2,3,4,6},py-{1,2,3,4,6},pt-{2,4,6},pb-{2,4,6},m-{0,1,2,4,auto},mt-{1,2,4},mb-{1,2,4},w-{full,fit,auto,px,4,8,10,12,16,24,32,40,48,56,64,72,80,96},h-{full,auto,4,8,10,12,16,24,32,40,48,64},min-w-{0,24,32,48},max-w-{xs,sm,md,lg,xl,none,full},min-h-{0,24,32},size-{4,6,8,10},shrink-0,grow,flex-1,text-{left,center,right},text-{xs,sm,base,lg,xl,2xl},font-{normal,medium,semibold,bold},leading-{none,tight,normal,relaxed},tracking-{tight,normal,wide},truncate,text-{foreground,muted-foreground,primary,destructive,card-foreground,accent-foreground,secondary-foreground},bg-{background,card,muted,accent,primary,secondary,destructive},border,border-{0,2,t,b,l,r},border-{border,input,muted,dashed},rounded-{none,sm,md,lg,xl,full},shadow-{none,xs,sm,md,lg},opacity-{50,70},overflow-{hidden,auto,x-auto},relative,absolute,inset-0,object-{cover,contain},aspect-{square,video},list-{none,disc},uppercase,capitalize,whitespace-nowrap,cursor-pointer,select-none,divide-y,antialiased}");
@import "tw-animate-css";

@theme inline {
${themeInline}
}

:root {
${light}
}

.dark {
${dark}
}

@layer base {
  * { border-color: var(--border); }
  body {
    background-color: var(--background);
    color: var(--foreground);
    font-family: var(--font-sans);
    -webkit-font-smoothing: antialiased;
  }
}
`;

writeFileSync(resolve(here, 'ds.in.css'), input);
execFileSync(
  resolve(repo, '.ds-sync/node_modules/.bin/tailwindcss'),
  ['-i', resolve(here, 'ds.in.css'), '-o', resolve(here, 'ds.css'), '--cwd', repo],
  { stdio: 'inherit' },
);
console.error('wrote .design-sync/assets/ds.css');
